"""Inventory every kit file; project maintained resources, never historical ownership."""
from pathlib import Path
import json, hashlib, re
from kit_companion_resources import COMPANION_RESOURCES
ROOT = Path(__file__).resolve().parents[3]
KIT = ROOT.parent / '901-resource-authoring-kit'
STAGE = Path(__file__).resolve().parent
def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()
def write(p,text):p.write_text(text,encoding='utf-8',newline='\r\n' if p.exists() and b'\r\n' in p.read_bytes() else '\n')
def dump(p, x): write(p,json.dumps(x, ensure_ascii=False, indent=2)+'\n')
def section(path, heading):
    lines=path.read_text(encoding='utf-8-sig').splitlines()
    start=next(i for i,s in enumerate(lines) if re.sub(r'^#+ ', '', s)==heading)
    depth=len(lines[start])-len(lines[start].lstrip('#'))
    end=next((i for i in range(start+1,len(lines)) if re.match(r'^#{1,'+str(depth)+r'} ',lines[i])),len(lines))
    return '\n'.join(lines[start:end]).strip(),start+1
def build():
    entries=[]
    def add(id,path,heading=None,kind='resource',**extra):
        p=KIT/path
        body,line=section(p,heading) if heading else (p.read_text(encoding='utf-8-sig').strip(),1)
        name=heading or body.splitlines()[0].lstrip('# ')
        item=dict(id=id,name=name,kind=kind,source='../901-resource-authoring-kit/'+path,line=line,body=body,sourceHash=digest(p),**extra)
        entries.append(item);return item
    coverage=json.loads((KIT/'resources/imperial-magic/校核/完整覆盖.json').read_text(encoding='utf-8'))
    seen=set()
    for row in coverage['records']:
        key=(row['output'],row['heading'])
        if key in seen: continue
        seen.add(key)
        add('imperial-magic:'+row['grade']+':'+row['heading'],row['output'],row['heading'],'spell',grade=row['grade'],prohibited=row['status']=='prohibited')
    assert sum(not x['prohibited'] for x in entries)==208
    assert sum(x['prohibited'] for x in entries)==7
    for file in ['00-施法通则','07-状态与特殊机制','08-炼金配方']:
        add('imperial-magic:'+file,'resources/imperial-magic/'+file+'.md',kind='rules')
    for name in ['guanlan-fa','fengyou-sheshibu','chengxin-xuanjian','imperial-mage','imperial-military','kuanglan','zheng-shiqi']:
        add(name,'resources/'+name+'.md',period='available-definition')
    for name in ['黄泉','姜子尤','布莱特','龙象般若功','乱红莲','弃风','狮子王']:
        add('later:'+name,'outputs/同伴RE资源调整/'+name+'.md',kind='character-template' if name in ['黄泉','姜子尤','布莱特'] else 'resource',period='later-optional',actor='御临风' if name=='弃风' else None)
    for actor,resources in COMPANION_RESOURCES.items():
        for heading,id in resources.items():
            item=add(id,'outputs/同伴RE资源调整/'+actor+'.md',heading,kind='resource',period='later-optional',actor=actor,sectionDepth=2)
            item['grade']=(re.search(r'\n\n([DCBAS])级',item['body']) or re.search(r'\n\n([DCBAS])／',item['body']))
            item['grade']=item['grade'].group(1) if item['grade'] else None
    files=[];byhash={}
    projected={x['source'].removeprefix('../901-resource-authoring-kit/') for x in entries}
    for p in sorted(KIT.rglob('*')):
        if not p.is_file() or '.git' in p.parts or '__pycache__' in p.parts:continue
        path=p.relative_to(KIT).as_posix();h=digest(p)
        category=('projected' if path in projected else 'authoring-evidence' if path.startswith('resources/') else 'later-archive' if path.startswith('outputs/同伴成长封存/') else 'historical-draft' if path.startswith('outputs/') else 'raw-reference' if path.startswith(('content/','source_archives/','source_html/','assets/')) else 'tools-and-index')
        files.append(dict(path=path,sha256=h,bytes=p.stat().st_size,category=category,duplicateOf=byhash.get(h)))
        byhash.setdefault(h,path)
    inventory=dict(files=files,entries=entries,policy='resources当前正文优先；原书为参考，旧稿不覆盖正文；成长模板不授予实际持有、不覆盖T0；禁术不开放学习。')
    dump(STAGE/'kit-inventory.json',inventory)
    write(ROOT/'work/rules_engine/resource-catalog.mjs','// Generated by kit_catalog.py; source definitions confer no ownership.\nexport const RESOURCE_CATALOG='+json.dumps({x['id']:x for x in entries},ensure_ascii=False,separators=(',',':'))+';\n')
    print(json.dumps(dict(files=len(files),entries=len(entries),spells=215),ensure_ascii=False))
if __name__=='__main__':build()
